// Rebuilds docs/upstream-tests.md from the `// Ported from:` headers of the
// bun:test files. Usage:
//   bun run scripts/reconcile-tests.ts <path-to-CLIProxyAPI-checkout> [<path-to-v7.0.12-checkout>]
// Every Go test file under test/, internal/ and sdk/ of the first checkout is
// listed. A file is "ported" when at least one TS test header names it, and
// its row links the TS files. Headers naming a file that exists in neither
// checkout are reported and make the script exit non-zero.
import { Glob } from "bun";
import { existsSync } from "node:fs";
import { join, relative } from "node:path";

const [upstream, legacy] = process.argv.slice(2);
if (!upstream) {
  console.error("usage: bun run scripts/reconcile-tests.ts <CLIProxyAPI checkout> [<v7.0.12 checkout>]");
  process.exit(2);
}
const repo = join(import.meta.dir, "..");

// 1. Collect "Ported from:" references from every TS test file.
const portedBy = new Map<string, Set<string>>();
for await (const file of new Glob("test/**/*.test.ts").scan(repo)) {
  const text = await Bun.file(join(repo, file)).text();
  const header = text.split("\n").slice(0, 40).join("\n");
  for (const m of header.matchAll(/Ported from:([^\n]*(?:\n\/\/\s+[^\n]*_test\.go[^\n]*)*)/g)) {
    for (const ref of m[1]!.matchAll(/((?:CLIProxyAPI-v[\d.]+\s+)?(?:test|internal|sdk)\/[\w./-]+_test\.go)/g)) {
      const go = ref[1]!.replace(/^CLIProxyAPI-v[\d.]+\s+/, "");
      if (!portedBy.has(go)) portedBy.set(go, new Set());
      portedBy.get(go)!.add(file);
    }
  }
}

// 2. Enumerate upstream tests.
const all: string[] = [];
for (const dir of ["test", "internal", "sdk"]) {
  for await (const f of new Glob(`${dir}/**/*_test.go`).scan(upstream)) all.push(f);
}
all.sort();

const missing = [...portedBy.keys()].filter((go) => !existsSync(join(upstream, go)) && !(legacy && existsSync(join(legacy, go))));

// 3. Skip reasons by area (kept short; the TS headers carry the per-case detail).
const specificReasons: Record<string, string> = {
  "test/builtin_tools_translation_test.go": "OpenAI chat and Responses inbound translators (inbound is Claude-only)",
  "test/claude_code_compatibility_sentinel_test.go": "asserts only the shape of its own Claude Code stream-json fixtures; no proxy code under test",
  "test/usage_logging_test.go": "usage statistics and request logging are not ported",
};

function skipReason(path: string): string {
  if (specificReasons[path]) return specificReasons[path]!;
  const b = path.slice(path.lastIndexOf("/") + 1);
  if (/benchmark|_bench_|perf_test|^race_/.test(b)) return "Go benchmark or race-detector harness";
  if (/antigravity|devin|kimi|xai|grok|meta_|vertex|iflow|qwen/.test(path)) return "dropped provider";
  if (path.includes("handlers/management") || path.includes("managementasset")) return "Management API (out of scope)";
  if (/translator\/(claude|interactions|antigravity)\//.test(path) || /translator\/(openai|gemini|codex)\/(openai|gemini|interactions)/.test(path)) return "non-Claude inbound format (out of scope)";
  if (/websocket|wsrelay|live/.test(path)) return "websocket / realtime transport (not ported)";
  if (/plugin|home|tui|watcher|redis|pprof|discovery|githubauth|safemode|homeplugins/.test(path)) return "infrastructure not carried over";
  if (/store\/(gitstore|postgres|objectstore)|config_seed/.test(path)) return "git/postgres/object stores (Vault + file only)";
  if (/siwc|apply_patch|imagegen|images|tool_search|web_search|compaction|compact|cloak|fingerprint|signing|diagnostics|multi_agent|session/.test(path)) return "feature not carried over";
  return "not ported (feature outside the kept paths)";
}

const ported = all.filter((p) => portedBy.has(p));
const lines: string[] = [
  "# Upstream test inventory",
  "",
  "Generated by `bun run scripts/reconcile-tests.ts <CLIProxyAPI checkout> <v7.0.12 checkout>` from the",
  "`// Ported from:` headers of the bun:test files. Source: router-for-me/CLIProxyAPI @ 9717e325",
  "(2026-10-28); v7.0.12 for the Gemini CLI OAuth path that current upstream no longer ships.",
  "",
  "Each ported test file's header lists the Go sub-cases it dropped and why. Rows marked *skip* were not",
  "ported; the reason is the area-level cause.",
  "",
  `Totals: ${all.length} upstream test files; ${ported.length} ported (fully or partly); ${all.length - ported.length} skipped.`,
  "",
];
const byDir = new Map<string, string[]>();
for (const p of all) {
  const d = p.slice(0, p.lastIndexOf("/"));
  if (!byDir.has(d)) byDir.set(d, []);
  byDir.get(d)!.push(p);
}
for (const [dir, files] of byDir) {
  lines.push(`## \`${dir}\``, "", "| Go test | Status | Ported as / reason |", "|---|---|---|");
  for (const f of files) {
    const name = f.slice(f.lastIndexOf("/") + 1);
    const by = portedBy.get(f);
    if (by) lines.push(`| \`${name}\` | ported | ${[...by].sort().map((t) => `\`${t}\``).join(", ")} |`);
    else lines.push(`| \`${name}\` | skip | ${skipReason(f)} |`);
  }
  lines.push("");
}
const legacyRefs = [...portedBy.keys()].filter((go) => !all.includes(go));
if (legacyRefs.length > 0) {
  lines.push("## Ported from v7.0.12 (not in current upstream)", "", "| Go test | Ported as |", "|---|---|");
  for (const go of legacyRefs.sort()) {
    if (missing.includes(go)) continue;
    lines.push(`| \`${go}\` | ${[...portedBy.get(go)!].sort().map((t) => `\`${t}\``).join(", ")} |`);
  }
  lines.push("");
}
await Bun.write(join(repo, "docs/upstream-tests.md"), lines.join("\n"));
console.log(`upstream=${all.length} ported=${ported.length} legacy=${legacyRefs.length - missing.length} unresolved=${missing.length}`);
if (missing.length > 0) {
  console.error("Headers naming Go files that do not exist:\n  " + missing.join("\n  "));
  process.exit(1);
}
void relative;
